const DICTS: Record<Lang, Dict> = { en, vi, es };

export type Vars = Record<string, string | number>;

export function translate(lang: Lang, key: Key, vars?: Vars): string {
  const s = DICTS[lang][key] ?? en[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s;
}

/** Pluralised lookup: `${base}.one` when n is 1 (and the language has it), else `${base}.other`. */
export function translatePlural(lang: Lang, base: string, n: number, vars?: Vars): string {
  const one = `${base}.one` as Key;
  const other = `${base}.other` as Key;
  const key = n === 1 && (DICTS[lang][one] ?? (lang === "en" ? en[one] : undefined)) ? one : other;
  return translate(lang, key, { n, ...vars });
}

/** Replace {name} placeholders in a translated string with React nodes. */
export function rich(text: string, nodes: Record<string, ReactNode>): ReactNode[] {
  return text.split(/(\{\w+\})/g).map((part, i) => {
    const m = /^\{(\w+)\}$/.exec(part);
    return m && m[1] in nodes ? <span key={i}>{nodes[m[1]]}</span> : part;
  });
}

/** Codes or names ("vi", "Vietnamese", "vi-VN") to a short code. */
export function langCode(s: string | null | undefined): string {
  const v = (s ?? "").trim().toLowerCase();
  if (!v) return "";
  const names: Record<string, string> = {
    vietnamese: "vi",
    "tiếng việt": "vi",
    spanish: "es",
    español: "es",
    castellano: "es",
    english: "en",
    catalan: "ca",
    valencian: "ca",
    french: "fr",
    german: "de",
  };
  return names[v] ?? v.split(/[-_]/)[0].slice(0, 3);
}

export function isLang(s: string): s is Lang {
  return (LANGS as string[]).includes(s);
}

/** The best UI language for a browser language list: vi, es, else English. */
export function preferredLang(list: readonly string[] = navigator.languages ?? [navigator.language]): Lang {
  for (const l of list) {
    const c = langCode(l);
    if (c === "vi" || c === "es" || c === "en") return c;
  }
  return "en";
}

export type Surface = "console" | "report";

interface I18n {
  lang: Lang;
  setLang(l: Lang): void;
  t(key: Key, vars?: Vars): string;
  tn(base: string, n: number, vars?: Vars): string;
}

const Ctx = createContext<I18n | null>(null);

function initialLang(surface: Surface): Lang {
  const q = new URLSearchParams(window.location.search).get("lang");
  if (q && isLang(q)) return q;
  try {
    const saved = localStorage.getItem(`floodline-lang-${surface}`);
    if (saved && isLang(saved)) return saved;
  } catch {
    /* private mode */
  }
  return surface === "console" ? "en" : preferredLang();
}

export function I18nProvider({ surface, children }: { surface: Surface; children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => initialLang(surface));
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const setLang = useCallback(
    (l: Lang) => {
      setLangState(l);
      try {
        localStorage.setItem(`floodline-lang-${surface}`, l);
      } catch {
        /* private mode */
      }
    },
    [surface],
  );
  const value = useMemo<I18n>(
    () => ({
      lang,
      setLang,
      t: (key, vars) => translate(lang, key, vars),
      tn: (base, n, vars) => translatePlural(lang, base, n, vars),
    }),
    [lang, setLang],
  );
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18n {
  const v = useContext(Ctx);
  if (!v) throw new Error("useI18n outside I18nProvider");
  return v;
}

/** A small EN | VI | ES switch. */
export function LangToggle({ langs = LANGS, className = "" }: { langs?: Lang[]; className?: string }) {
  const { lang, setLang, t } = useI18n();
  return (
    <div className={`langtoggle ${className}`} role="group" aria-label={t("lang.label")}>
      {langs.map((l) => (
        <button
          key={l}
          type="button"
          className={l === lang ? "is-on" : ""}
          aria-pressed={l === lang}
          title={LANG_NAME[l]}
          lang={l}
          onClick={() => setLang(l)}
        >
          {l.toUpperCase()}
        </button>
      ))}
    </div>
  );
}
